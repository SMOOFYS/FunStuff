# Load JSON file for questions
def load_questions(subject):
    """
    The function fetches the questions under the desired subject from my .json file,
    loading those questions under that subject category into this file and then 
    returning all of those questions.

    Parameter:

    subject -> the desired subject that the quiz taker wishes to study

    Returns:

    data[subject] -> these are all of the questions for the desired subject
    """
    with open('subjects.json', 'r') as file:
        data = json.load(file)
        return data[subject]

