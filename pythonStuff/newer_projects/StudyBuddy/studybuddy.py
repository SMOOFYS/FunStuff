def check_answer(question, user_answer):
    """
    this function uses the question dictionary from the questions list and fetches the answer to the question, 
    whilst checking it against the user input

    Parameters:

    question -> the question that you want the answer for
    user_answer -> The users answer to the question

    Returns: 

    question['answer'] == user_answer.upper() -> returns a True or False statement for whether or not the user got a correct answer or not.
    """
    return question['answer'] == user_answer.upper()

