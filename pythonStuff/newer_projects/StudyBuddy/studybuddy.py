def start_quiz(subject):
    """
    The primary quiz system. First, it uses the load_questions() to grab the list of questions.
    Afterwards, it grabs the total number of questions to use for the display_scores() to calculate the user's grade at the end. 
    Then, it takes the user selected subject and uses a for loop to go through each question for that subject, using an if statement and the check_answer() to check if the user got the answer right or not.
    Afterwards, the compiled data of total answers right and the total number of questions are inputed into the display_scores() to display results and statistics.

    Parameters:

    subject -> the subject that the user wants to take a quiz on

    Returns:

    None, just the loop of questions for the subject, with a display of their statistics then leading back to the main menu.
    """
    print(f"Starting quiz on {subject}", end="")
    for i in range(3):
        time.sleep(0.75)
        print(".", end="", flush=True) # <- flush is used to make sure my 3 dot animation for the "starting quiz" intro actually works cuz for some reason it doesn't work w/o it
    time.sleep(0.5)
    questions = load_questions(subject)
    total_questions = len(questions)
    random.shuffle(questions)

    correct_answers = 0
    
    
    for question in questions:
        print(f"\n{question['question']}")
        for option in question['options']:
            print(option)
        user_answer = input("Your answer (A, B, C, etc.): ").strip().upper()

        if check_answer(question, user_answer):
            print("Correct!\n")
            correct_answers += 1
        else:
            print(f"Wrong! The correct answer was {question['answer']}.\n")

    display_scores(correct_answers, total_questions)

def main_menu():
    """
    The main function to which all the functions run under, and is controlled by a while loop to let the user take the quiz for any subject for any amount of times, with the option to quit whenever. 
    It uses the greeting() to start off the program, and then the while loop is incorporated.

    Parameters:

    None

    Returns:

    None
    """
    greeting()
    while True:
        print("Main Menu:\n1. AP European History Quiz\n2. Honors Chemistry Quiz\n3. Pre-Calculus\n4. Computer Science and Programming (CSP)\n5. Quit")
        choice = input("Choose an option (1, 2, 3, 4, 5): ").strip()
        if choice == '1':
            start_quiz("AP Euro")
        elif choice == '2':
            start_quiz("Honors Chemistry")
        elif choice == '3':
            start_quiz("Pre-Calculus")
        elif choice == '4':
            start_quiz("CSP")
        elif choice == '5':
            print("Thank you for using the Study Buddy, Goodbye!")
            break
        else:
            print("Invalid choice. Please try again.\n")

main_menu()

